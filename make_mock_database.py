"""Make a MOCK multi-subject database for demos and testing.

    python make_mock_database.py                 # 10 mock subjects
    python make_mock_database.py --subjects 30

Takes every trial of the first real subject in database/rtp_database.h5 and
creates N synthetic subjects (MOCK_001, MOCK_002, ...) from it:

  * each mock subject gets its own gain (+-15 %) and offset per signal and
    per metric, so subjects differ from each other consistently;
  * each trial adds small noise, so trials within a subject differ a little;
  * event times are unchanged, so time-normalization still works;
  * sex / height / weight are randomized.

The data are FAKE - for trying out the database layout, the dashboard and
multi-subject analysis code only. The file is flagged mock=True and every
subject ID starts with MOCK_. It is written to database/mock_database.h5 and
never touches the real database.
"""

from __future__ import annotations

import argparse
import os
import sys
from datetime import datetime
from pathlib import Path

import h5py
import numpy as np
import pandas as pd

import v3d_db as db
from rtp_ingest import write_table

HERE = Path(__file__).resolve().parent


def jitter_signal(data: np.ndarray, gain: float, offset: np.ndarray, rng) -> np.ndarray:
    """Subject-level gain/offset plus a smooth per-trial wobble."""
    n = len(data)
    spread = np.nanstd(data, axis=0)
    spread = np.where(np.isfinite(spread) & (spread > 0), spread, 1.0)
    wobble = np.cumsum(rng.normal(0, 1, size=data.shape), axis=0)
    wobble = (wobble - wobble.mean(axis=0)) / (np.abs(wobble).max(axis=0) + 1e-9)
    out = data * gain + offset * spread + 0.05 * spread * wobble
    return out.astype(np.float32) if n else data


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--subjects", type=int, default=10)
    ap.add_argument("--source", type=Path, default=db.DEFAULT_DB)
    ap.add_argument("--out", type=Path, default=HERE / "database" / "mock_database.h5")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    if not args.source.exists():
        print(f"{args.source} not found - run `python rtp_ingest.py` first")
        return 1
    rng = np.random.default_rng(args.seed)
    trials = db.trials(db_path=args.source)
    src_subject = sorted(trials["subject"].unique())[0]
    t_src = trials[trials["subject"] == src_subject]
    events = db._get("events", args.source)
    metrics = db._get("metrics", args.source)
    print(f"Template: {len(t_src)} trials of {src_subject}; making {args.subjects} mock subjects")

    tmp = args.out.with_suffix(".h5.tmp")
    new_trials, new_events, new_metrics = [], [], []
    with h5py.File(args.source, "r") as src, h5py.File(tmp, "w") as out:
        out.attrs.update(mock=True, schema_version="1", created=datetime.now().isoformat(timespec="seconds"),
                         note="SYNTHETIC DATA generated by make_mock_database.py - not real subjects")
        for k in range(1, args.subjects + 1):
            sid = f"MOCK_{k:03d}"
            sgrp = out.create_group(f"subjects/{sid}")
            sgrp.attrs.update(sex=str(rng.choice(["Male", "Female"])),
                              dominance=str(rng.choice(["Right", "Left"], p=[0.85, 0.15])))
            height = float(np.clip(rng.normal(1.75, 0.09), 1.5, 2.05))
            weight = float(np.clip(rng.normal(75, 12), 50, 120))
            sig_gain, sig_off, met_gain = {}, {}, {}

            for _, tr in t_src.iterrows():
                session = tr["session"]
                sess_grp = out.require_group(f"subjects/{sid}/{session}")
                sess_grp.attrs.update({**dict(src[f"subjects/{src_subject}/{session}"].attrs),
                                       "height_m": height, "weight_kg": weight,
                                       "injured_side": str(rng.choice(["Left", "Right", "None"]))})
                old_path = tr["trial_path"]
                new_path = old_path.replace(f"/subjects/{src_subject}/", f"/subjects/{sid}/")
                g_src, g_new = src[old_path], out.create_group(new_path)
                g_new.attrs.update({**dict(g_src.attrs), "source_file": f"MOCK copy of {g_src.attrs['source_file']}",
                                    "source_export": "mock"})

                def copy(name, obj):
                    if not isinstance(obj, h5py.Dataset):
                        return None
                    sig = obj.attrs.get("name", name)
                    if sig not in sig_gain:  # one gain/offset per subject and signal
                        sig_gain[sig] = float(np.clip(rng.normal(1.0, 0.07), 0.85, 1.15))
                        sig_off[sig] = rng.normal(0, 0.15, size=obj.shape[1])
                    ds = g_new.create_dataset(f"signals/{name}", data=jitter_signal(obj[:], sig_gain[sig], sig_off[sig], rng),
                                              compression="gzip", compression_opts=4)
                    ds.attrs.update(dict(obj.attrs))
                    return None

                g_src["signals"].visititems(copy)

                new_trials.append({**tr.to_dict(), "trial_path": new_path, "subject": sid,
                                   "source_file": f"MOCK copy of {tr['source_file']}"})
                ev = events[events["trial_path"] == old_path].assign(trial_path=new_path)
                new_events.append(ev)
                m = metrics[metrics["trial_path"] == old_path].copy()
                gains = np.array([met_gain.setdefault(n, float(np.clip(rng.normal(1.0, 0.07), 0.85, 1.15))) for n in m["name"]])
                m["value"] = m["value"] * gains * rng.normal(1.0, 0.02, size=len(m))
                new_metrics.append(m.assign(trial_path=new_path))
            print(f"  {sid}")

        tables = out.create_group("tables")
        write_table(tables.create_group("trials"), pd.DataFrame(new_trials))
        write_table(tables.create_group("events"), pd.concat(new_events, ignore_index=True))
        write_table(tables.create_group("metrics"), pd.concat(new_metrics, ignore_index=True))

    os.replace(tmp, args.out)
    print(f"\nWrote {args.out}  ({args.out.stat().st_size / 1e6:.0f} MB) - MOCK DATA")
    return 0


if __name__ == "__main__":
    sys.exit(main())
